"""
SQLAlchemy 2.x Artifact Model for JARVIS
Tracks persistent filesystem, document, and code artifacts generated by tasks.
"""

from __future__ import annotations

import datetime
import uuid
from typing import Any, Dict, Optional
import sqlalchemy as sa
from sqlalchemy.orm import Mapped, mapped_column, relationship

from jarvis.db.models.base import Base, GUID, UniversalJSON


class ArtifactModel(Base):
    __tablename__ = "artifacts"

    id: Mapped[uuid.UUID] = mapped_column(GUID, primary_key=True, default=uuid.uuid4)
    task_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        GUID, sa.ForeignKey("tasks.id", ondelete="SET NULL"), index=True, nullable=True
    )
    artifact_type: Mapped[str] = mapped_column("type", sa.String(50), index=True, nullable=False)
    location: Mapped[str] = mapped_column(sa.Text, nullable=False)
    checksum: Mapped[str] = mapped_column(sa.String(64), nullable=False, default="")
    metadata_json: Mapped[Dict[str, Any]] = mapped_column("metadata", UniversalJSON, default=dict, nullable=False)
    created_at: Mapped[datetime.datetime] = mapped_column(
        sa.DateTime(timezone=True),
        default=lambda: datetime.datetime.now(datetime.timezone.utc),
        nullable=False,
    )

    # Relationships
    task: Mapped[Optional["TaskModel"]] = relationship("TaskModel", back_populates="artifacts")
